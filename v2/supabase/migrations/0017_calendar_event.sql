-- ║  Google 日曆事件 id                                        ║
-- ╚══════════════════════════════════════════════════════════╝
--
-- 舊系統（GAS）是「用系統ID去日曆裡搜尋前後 90 天，找到就刪掉重畫」——
-- 因為 Firestore 那邊沒地方存事件 id。搜尋很慢、範圍外的改不到，
-- 而且同一筆改時間就會變成刪一個、建一個，日曆上的提醒也跟著重來。
--
-- 這裡直接把事件 id 存在預約上：改時間就 PATCH 同一個事件，取消才刪。
-- null＝還沒同步過（或同步失敗），下次有動作時會重建。
alter table bookings add column if not exists calendar_event_id text;
